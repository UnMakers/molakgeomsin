# 갈림길 인장: 경구 같은 둘째 줄을 걷어 낸다. 희생의 한 줄("너는 잊겠지만, 나는 기억한다.")만 남긴다.
MARK_KEEP = '너는 잊겠지만, 나는 기억한다.'

import re
mark_rx = re.compile(r'(@mark text:"[^"]*")( note:"([^"]*)")')

total = {o: 0 for o, n in R}
for p in sorted(glob.glob(os.path.join(C, '*.nani'))):
    s = io.open(p, encoding='utf-8').read(); s0 = s
    for o, n in R:
        c = s.count(o)
        if c: total[o] += c; s = s.replace(o, n)
    s = mark_rx.sub(lambda m: m.group(1) + (m.group(2) if m.group(3) == MARK_KEEP else ''), s)
    if s != s0: io.open(p, 'w', encoding='utf-8').write(s)
miss = [o for o, c in total.items() if c == 0]
if miss:
    print('MISSING:'); [print('  ', m[:60]) for m in miss]; sys.exit(1)
print('tone ok', sum(total.values()))
